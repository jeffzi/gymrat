def compute_half_range(values: Sequence[float]) -> float:
    """Return half the span ``(max - min) / 2`` of ``values``.

    A single non-finite sample poisons the whole result rather than being
    dropped, so the span never silently narrows and never reads as ±infinity.

    Args:
        values: The samples to summarize. Must be non-empty.

    Returns:
        Half the span over finite samples, or ``float("nan")`` when any sample
        is non-finite.

    Raises:
        ValueError: If ``values`` is empty.
    """
    if not values:
        msg = "compute_half_range requires at least one sample; got an empty sequence"
        raise ValueError(msg)
    if any(not math.isfinite(sample) for sample in values):
        return math.nan
    return (max(values) - min(values)) / 2.0


def percent_delta(reference: float, value: float) -> float:
    """Return the percent change of ``value`` against ``reference``'s magnitude.

    Dividing by the magnitude keeps the sign tied to the direction the value
    moved: a negative reference rising toward zero is an increase, and one
    dropping further below zero is a decrease. When the reference is zero the
    ratio is undefined, so the caller decides how to treat the ``NaN``.

    Args:
        reference: The value the change is measured from.
        value: The value compared against ``reference``.

    Returns:
        ``(value - reference) / abs(reference) * 100``, ``0.0`` when both are
        zero, or ``NaN`` when only ``reference`` is zero.
    """
    if reference == 0:
        return 0.0 if value == 0 else math.nan
    return (value - reference) / abs(reference) * 100


def normalize_ratio(
    delta: float, direction: Direction
) -> float | Literal["undefined-ratio", "infinite-rho"]:
    """Normalize a percent ``delta`` into a ratio rho for the given direction.

    For ``"lower"``, ``rho = 1 + delta / 100``. For ``"higher"``,
    ``rho = 1 / (1 + delta / 100)``. A rho that is not strictly positive and
    finite cannot be combined in log space, so it is reported as an exclusion.

    Args:
        delta: The percent delta to normalize.
        direction: Whether a lower or higher raw value is the improvement.

    Returns:
        The usable rho, or ``"undefined-ratio"`` when ``delta`` is NaN, or
        ``"infinite-rho"`` when the resulting rho is non-positive or non-finite.
    """
    if math.isnan(delta):
        return "undefined-ratio"
    rho = 1.0 + delta / 100.0
    if direction == "higher":
        # A zero factor would divide by zero; route it to the infinite-rho
        # exclusion below instead of raising.
        rho = 1.0 / rho if rho != 0.0 else math.inf
    if rho <= 0.0 or not math.isfinite(rho):
        return "infinite-rho"
    return rho


def combine_geomean(entries: Sequence[tuple[float, float]]) -> tuple[float, float]:
    """Combine included ``(rho, noise_pct)`` entries via the geometric mean.

    Args:
        entries: The included entries, each a ``(rho, noise_pct)`` pair. Every
            ``rho`` must be strictly positive.

    Returns:
        A ``(value, band)`` pair: the geometric mean of the ratios as a percent
        change, ``(exp(mean(ln rho)) - 1) * 100``, and the per-entry noise
        combined in quadrature, ``sqrt(sum(noise_pct**2)) / n``. Empty input
        yields two zeros; a single entry yields that rho as a percent change
        with its own noise as the band.
    """
    if not entries:
        return 0.0, 0.0
    value = (statistics.geometric_mean(rho for rho, _ in entries) - 1.0) * 100.0
    band = math.hypot(*(noise_pct for _, noise_pct in entries)) / len(entries)
    return value, band


# ---------------------------------------------------------------------------
# Paired permutation test
# ---------------------------------------------------------------------------

# The permutation needs at least two paired observations; a single pair admits
# only the trivial sign flip and carries no null spread to test against.
_MIN_PAIRS = 2

RESAMPLE_BUDGET = 9999
"""Upper bound on sign-flip resamples.

When the exact null space ``2**pairs`` is at most this budget, every sign flip
is enumerated (exact test); above it, this many Monte Carlo resamples are drawn.
The value brackets the exact/Monte Carlo seam at ``pairs == 13``: ``2**13 ==
8192`` still enumerates exactly, while ``2**14 == 16384`` crosses into sampling.
"""

PERMUTATION_SEED = 12345
"""Fixed RNG seed for the Monte Carlo path, making sampled p-values reproducible."""


def _paired_differences(x: Sequence[float], y: Sequence[float]) -> list[float]:
    """Return ``y[i] - x[i]`` for the differing pairs, paired over the shorter input."""
    return [yi - xi for xi, yi in zip(x, y, strict=False) if xi != yi]


def count_nonzero_pairs(x: Sequence[float], y: Sequence[float]) -> int:
    """Pair ``x`` and ``y`` positionally over the shorter input and count differing pairs.

    Shared by every paired significance test: each pairs ``x[i]`` with ``y[i]``
    for ``i`` below the shorter input's length.  A pair is tied when its values
    compare equal (``x[i] == y[i]``) and differing otherwise, so a pair of equal
    infinities is tied and a pair holding a NaN always differs.  The sign-flip
    test leaves tied pairs out, so this count is the ``n`` its null space spans.

    Args:
        x: The first sample.
        y: The second sample, paired positionally with ``x``.

    Returns:
        How many of the paired positions hold values that differ
        (``x[i] != y[i]``).
    """
    return len(_paired_differences(x, y))


class SignFlipResult(NamedTuple):
    """Outcome of :func:`sign_flip_permutation_test`.

    Attributes:
        p: The two-sided p-value, always within ``[0.0, 1.0]``.
        statistic: The Wilcoxon signed-rank sum of the paired differences
            ``y[i] - x[i]``: positive when the ranks favor increases, negative
            when they favor decreases, ``0.0`` when they balance or no pair
            differs, and NaN when a difference is NaN.
    """

    p: float
    statistic: float


def _signed_rank_statistic(
    differences: "NDArray[np.float64]", axis: int
) -> "np.float64 | NDArray[np.float64]":
    import numpy as np  # noqa: PLC0415 -- deferred: import-latency guard
    from scipy.stats import rankdata  # noqa: PLC0415 -- deferred: import-latency guard  # pyrefly: ignore[untyped-import] -- scipy ships no stubs

    # Average ranks give equal magnitudes one shared rank, so the statistic, and
    # the p-value built on it, does not depend on the order of the pairs.
    ranks = rankdata(np.abs(differences), axis=axis)
    return np.sum(np.sign(differences) * ranks, axis=axis)


def sign_flip_permutation_test(x: Sequence[float], y: Sequence[float]) -> SignFlipResult:
    """Run a two-sided sign-flip permutation test on index-paired samples.

    The test statistic is the Wilcoxon signed-rank sum over the ``n`` differing
    pairs' differences ``d_i = y[i] - x[i]``: tied pairs are left out, the
    absolute differences are ranked with average ranks so equal magnitudes share
    a rank, and each rank carries its difference's sign. An infinite difference
    ranks as the largest magnitude. Each sign flip negates one ``d_i``, so the
    null space is ``2**n``. When ``2**n`` fits :data:`RESAMPLE_BUDGET` the
    enumeration is exact; otherwise :data:`RESAMPLE_BUDGET` Monte Carlo resamples
    are drawn from a generator seeded with :data:`PERMUTATION_SEED`. Both paths
    are deterministic for a given input.

    Args:
        x: The baseline sample.
        y: The candidate sample, paired positionally with ``x`` over the shorter of
            the two; trailing entries of the longer input are ignored.

    Returns:
        The p-value and the signed-rank sum. The statistic is computed on every
        path; the p-value is ``1.0`` when fewer than two pairs differ or any
        differing pair's difference is NaN.
    """
    import numpy as np  # noqa: PLC0415 -- deferred: import-latency guard

    differences = np.asarray(_paired_differences(x, y), dtype=np.float64)
    if differences.size < _MIN_PAIRS or np.isnan(differences).any():
        statistic = _signed_rank_statistic(differences, axis=-1)
        return SignFlipResult(p=1.0, statistic=float(statistic))

    from scipy.stats import permutation_test  # noqa: PLC0415 -- deferred: import-latency guard  # pyrefly: ignore[untyped-import] -- scipy ships no stubs

    # With one sample, "samples" permutations flip the sign of each observation;
    # scipy enumerates all 2**n sign flips itself whenever they fit the budget.
    result = permutation_test(
        (differences,),
        _signed_rank_statistic,
        permutation_type="samples",
        alternative="two-sided",
        vectorized=True,
        n_resamples=RESAMPLE_BUDGET,
        rng=np.random.default_rng(PERMUTATION_SEED),
    )
    return SignFlipResult(p=float(result.pvalue), statistic=float(result.statistic))


# ---------------------------------------------------------------------------
# Detectable shift
# ---------------------------------------------------------------------------

_DETECTION_ALPHA = 0.05

# With every pair differing and sharing one sign, exact enumeration gives
# p = 2 / 2**n, the smallest it can reach; it first drops below 0.05 at n = 6.
_MIN_DETECTABLE_PAIRS = 6

# Each check runs the permutation test twice, and above 13 pairs each run draws
# RESAMPLE_BUDGET resamples, so the search stops after this many checks and falls
# back to the shift that gives every centered difference one sign.
_MAX_SHIFT_CHECKS = 3


def _walsh_averages(values: Sequence[float]) -> list[float]:
    return [(values[i] + values[j]) / 2 for i in range(len(values)) for j in range(i, len(values))]


def _critical_rank_sum(pairs: int) -> int:
    """The smallest positive rank sum whose two-sided exact p is below ``_DETECTION_ALPHA``.

    The null distribution is the tie-free Wilcoxon signed-rank one: each rank
    ``1..pairs`` joins the positive sum with probability one half.

    Args:
        pairs: How many paired differences the test ranks.

    Returns:
        The critical positive rank sum.
    """
    import numpy as np  # noqa: PLC0415 -- deferred: import-latency guard

    total = pairs * (pairs + 1) // 2
    probabilities = np.zeros(total + 1)
    probabilities[0] = 1.0
    for rank in range(1, pairs + 1):
        with_rank = np.zeros_like(probabilities)
        with_rank[rank:] = probabilities[:-rank]
        probabilities = (probabilities + with_rank) / 2
    upper_tails = np.cumsum(probabilities[::-1])[::-1]
    return int(np.argmax(2 * upper_tails < _DETECTION_ALPHA))


def _detected_both_ways(centered: Sequence[float], shift: float) -> bool:
    zeros = [0.0] * len(centered)
    raised = sign_flip_permutation_test(zeros, [c + shift for c in centered])
    lowered = sign_flip_permutation_test(zeros, [c - shift for c in centered])
    return raised.p < _DETECTION_ALPHA and lowered.p < _DETECTION_ALPHA


def detectable_shift(x: Sequence[float], y: Sequence[float]) -> float:
    """Return a shift of the paired differences the sign-flip test detects either way.

    The paired differences ``y[i] - x[i]``, tied pairs included, are centered on
    their Hodges-Lehmann estimate: the median of their pairwise (Walsh)
    averages. The detectable shift is an ``s >= 0`` for which
    :func:`sign_flip_permutation_test` reaches ``p < 0.05`` on both the
    centered differences plus ``s`` and the centered differences minus ``s``,
    so a change of that size in either direction would register. It is the
    smallest such ``s`` for tie-free differences with at most 13 differing
    pairs, where the test enumerates every sign flip; with ties or more pairs
    it is the first candidate the upward search below confirms.

    Significance can only change where a shifted difference meets zero or the
    negation of another, that is at the magnitude of one of the centered
    differences' pairwise averages, and at such a point the tie it creates can
    keep the test short of significance. The shift returned therefore sits a
    few units in the last place above that point. The Hodges-Lehmann interval
    over the pairwise averages names the first candidate point; it matches the
    test exactly only for tie-free differences under exact enumeration, so each
    candidate is checked with the real test and the search moves up to the next
    point when the check fails. After a few failed checks it settles on the
    shift that gives every centered difference one sign, which always
    registers.

    Args:
        x: The baseline sample.
        y: The candidate sample, paired positionally with ``x`` over the shorter
            of the two.

    Returns:
        The detectable shift, in the units of the samples. ``math.inf`` when
        there are too few pairs for any shift to reach significance (fewer than
        six), and ``math.nan`` when a paired difference is not finite.
    """
    differences = [yi - xi for xi, yi in zip(x, y, strict=False)]
    if not all(math.isfinite(d) for d in differences):
        return math.nan
    if len(differences) < _MIN_DETECTABLE_PAIRS:
        return math.inf

    center = statistics.median(_walsh_averages(differences))
    centered = [d - center for d in differences]
    averages = sorted(_walsh_averages(centered))
    widest = max(abs(c) for c in centered)

    # Raising by s makes the positive rank sum count the averages above -s;
    # lowering makes the negative one count those below s. Both must reach the
    # critical count.
    critical = _critical_rank_sum(len(centered))
    start = max(-averages[len(averages) - critical], averages[critical - 1], 0.0)
    points = sorted({abs(a) for a in averages if abs(a) > start})
    for point in [start, *points][:_MAX_SHIFT_CHECKS]:
        shift = _just_above(point, widest)
        if _detected_both_ways(centered, shift):
            return shift
    return _just_above(widest, widest)


def _just_above(point: float, widest: float) -> float:
    # A shifted difference is at most `widest + point` in magnitude, so a few
    # units in its last place keep every sum `c + shift` from rounding back
    # onto the tie at `point`.
    return point + 4 * math.ulp(widest + point)
