"""Pure statistics helpers: descriptive summaries and a paired permutation test.

Nothing here performs I/O, formats output, or reads configuration. Beyond the
standard library, only :data:`~gymrat.model.Direction` is imported at module
level, as a lightweight type alias.

``compute_half_range`` treats empty input as a programming error — callers are
expected to have samples — and raises a plain :class:`ValueError` rather than a
domain error.  ``combine_geomean`` accepts empty input and returns zeros.

``sign_flip_permutation_test`` is a sign-flip permutation test over
index-paired samples. It pairs ``x`` and ``y`` positionally over the shorter
input and asks whether the Wilcoxon signed-rank sum of the paired differences
could plausibly arise under the null hypothesis of no effect. Under that null a
paired observation is exchangeable with its partner, so the null distribution
is generated by flipping the sign of each differing pair's difference:
enumerated exhaustively when the ``2**n`` sign-flip space over the ``n``
differing pairs fits the resample budget (tied pairs stay out of the flips), and
sampled with a fixed seed above it. Either way the reported p-value is
deterministic for a given input. The test returns a :class:`SignFlipResult`
carrying both the p-value and the signed-rank sum, so callers read the
direction of the change from the same call. ``numpy`` and ``scipy`` are
imported inside function bodies, so importing this module never pulls them in.
"""

import math
import statistics
from collections.abc import Sequence
from typing import TYPE_CHECKING, Literal, NamedTuple

from gymrat.model import Direction

if TYPE_CHECKING:
    import numpy as np
    from numpy.typing import NDArray

__all__ = [
    "RESAMPLE_BUDGET",
    "SignFlipResult",
    "combine_geomean",
    "compute_half_range",
    "count_nonzero_pairs",
    "detectable_shift",
    "normalize_ratio",
    "percent_delta",
    "sign_flip_permutation_test",
]

