"""Markdown reference document generation from JSON schemas and readers.

``render_reference(schemas, readers)`` takes the two JSON Schema dicts from
``render_json_schemas()`` and the ``READERS`` dict from ``asyncapi.py``,
returning a Markdown document with a generated-file banner, per-log sections,
per-record/event subsections with field tables, nested-object subsections,
and a closing Readers section.
"""

import re

import pytest

from gymrat.event_docs.asyncapi import READERS, SESSION_LOG_ADDRESS, SUPERVISOR_LOG_ADDRESS
from gymrat.event_docs.json_schema import render_json_schemas
from gymrat.session.paths import SESSION_LOG_NAME, supervisor_log_name


def _render() -> str:
    from gymrat.event_docs.reference import render_reference

    schemas = render_json_schemas()
    return render_reference(schemas, READERS)


def _intro(md: str) -> str:
    intro_end = md.find("\n## ")
    return md[:intro_end]


def _section_for_type(md: str, wire_type: str) -> str:
    start = md.find(f"\n### `{wire_type}`\n")
    next_heading = md.find("\n### ", start + 1)
    return md[start:next_heading] if next_heading != -1 else md[start:]


def _readers_section(md: str) -> str:
    readers_start = md.find("## Readers")
    return md[readers_start:]


