def test_render_reference_when_called_does_wrap_prose_at_100_columns():
    md = _render()

    for line in md.split("\n"):
        is_table = line.lstrip().startswith("|")
        is_html_comment = line.lstrip().startswith("<!--")
        if is_table or is_html_comment:
            continue
        assert len(line) <= 100, f"line exceeds 100 columns ({len(line)} chars): {line[:120]!r}"


def test_render_reference_when_called_does_end_with_single_trailing_newline():
    md = _render()

    assert md.endswith("\n")
    assert not md.endswith("\n\n")


def test_render_reference_when_called_does_have_no_trailing_spaces():
    md = _render()

    for i, line in enumerate(md.split("\n"), 1):
        assert line == line.rstrip(" "), f"line {i} has trailing spaces: {line!r}"


