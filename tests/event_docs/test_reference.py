def _assert_sections_in_declared_order(md: str, wire_order: list[str], label: str) -> None:
    positions = []
    for wire_type in wire_order:
        pos = md.find(f"\n### `{wire_type}`\n")
        assert pos != -1, f"missing section for {wire_type}"
        positions.append(pos)

    assert positions == sorted(positions), f"{label} sections out of order: {wire_order}"


def test_render_reference_when_called_does_order_session_sections_per_union_declaration():
    md = _render()

    _assert_sections_in_declared_order(md, _SESSION_WIRE_ORDER, "session")


def test_render_reference_when_called_does_order_supervisor_sections_per_union_declaration():
    md = _render()

    _assert_sections_in_declared_order(md, _SUPERVISOR_WIRE_ORDER, "supervisor")


