def test_render_reference_when_called_does_have_table_header_with_four_columns():
    md = _render()

    table_header_pattern = re.compile(
        r"\| *Name *\| *Type *\| *Status *\| *Description *\|"
        r"|\| *name *\| *type *\| *required/optional *\| *description *\|",
        re.IGNORECASE,
    )

    assert table_header_pattern.search(md), "field table header not found"


def _field_row(section: str, field: str) -> str:
    rows = [line for line in section.split("\n") if field in line and "|" in line]
    assert len(rows) >= 1
    return rows[0]


def test_render_reference_when_called_does_mark_required_fields_as_required():
    md = _render()

    iteration_section = _section_for_type(md, "iteration")

    assert "required" in _field_row(iteration_section, "seq").lower()


def test_render_reference_when_called_does_mark_optional_fields_as_optional():
    md = _render()

    iteration_section = _section_for_type(md, "iteration")

    assert "optional" in _field_row(iteration_section, "duration_ms").lower()


def test_render_reference_when_called_does_mark_const_type_discriminator_as_required():
    md = _render()

    tool_start_section = _section_for_type(md, "tool_start")
    type_row = [
        line for line in tool_start_section.split("\n") if "| `type`" in line and "|" in line
    ]

    assert len(type_row) >= 1, "no type row found in tool_start section"
    assert "required" in type_row[0].lower(), (
        f"expected const type to be marked required, got: {type_row[0]!r}"
    )


